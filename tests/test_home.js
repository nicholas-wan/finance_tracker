const assert = require('node:assert/strict');
const { actions, days, nextService, warrantyState, needsInformation } = require('../app/js/home.js');
assert.equal(warrantyState('2026-09-04','2026-09-05'),'expired');
assert.equal(warrantyState('2026-09-05','2026-09-05'),'today');
assert.equal(warrantyState('2026-09-06','2026-09-05'),'active');
assert.equal(warrantyState('','2026-09-05'),'unknown');
assert.equal(days('2026-09-05', '2026-09-05'), 0);
assert.equal(nextService({lastService:'2024-01-31',frequencyMonths:1}), '2024-02-29');
assert.equal(nextService({lastService:'2025-01-31',frequencyMonths:1}), '2025-02-28');
assert.equal(nextService({lastService:'2025-01-31',frequencyMonths:1,nextService:'2025-03-02'}), '2025-03-02');
let result=actions([{kind:'insurance',status:'Needs checking',expires:'2025-09-24',name:'Policy'}], '2026-09-05');
assert.equal(result[0].label, 'Check latest renewal');
assert.equal(result[0].tone, 'past');
assert.ok(!JSON.stringify(result).includes('uninsured'));
assert.equal(actions([{kind:'insurance',status:'Archived',expires:'2025-01-01'}], '2026-09-05').length,0);
assert.equal(actions([{kind:'appliance',status:'Verified',installed:'2024-01-01',expires:'2025-01-01'}], '2026-09-05').length,0);
assert.equal(actions([{kind:'appliance',status:'Verified',expires:'2027-01-01'}], '2026-09-05')[0].label,'Add delivery or installation date');
assert.equal(actions([{kind:'appliance',status:'Verified',expires:'2025-01-01'}], '2026-09-05').length,0,'an expired warranty no longer needs a delivery date');
assert.equal(actions([{kind:'appliance',status:'Verified',warrantyStatus:'expired'}], '2026-09-05').length,0);
assert.equal(actions([{kind:'appliance',status:'Verified',warrantyStatus:'not_applicable'}], '2026-09-05').length,0);
assert.equal(actions([{kind:'appliance',status:'Verified',expires:'2025-01-01',secondaryExpiry:'2029-01-01'}], '2026-09-05')[0].label,'Add delivery or installation date');
assert.equal(needsInformation({kind:'appliance',status:'Verified',warrantyStatus:'expired'}),false);
result=actions([{kind:'mortgage',status:'Verified',lockInEnd:'2026-12-01',noticeDays:120}], '2026-09-05');
assert.equal(result[0].date, '2026-08-03');
assert.equal(result[0].label, 'Suggested mortgage review');
assert.equal(actions([{kind:'mortgage',status:'Verified',lockInEnd:'2026-12-01',reviewDate:'2027-06-01'}], '2026-09-05').length,0);
result=actions([{kind:'appliance',status:'Verified',installed:'2024-10-03',expires:'2027-10-02',secondaryWarranty:'Compressor',secondaryExpiry:'2029-10-02'}], '2029-09-05');
assert.equal(result.length,1);
assert.equal(result[0].label,'Compressor ends');
assert.equal(result[0].date,'2029-10-02');
console.log('Home date and reminder tests passed.');
